def label_rank(column: SQLColumnExpression[Any], labels: dict[str, str]) -> SQLColumnExpression[Any]:
    ordered = sorted(labels, key=lambda code: (labels[code].casefold(), code))
    return case({code: rank for rank, code in enumerate(ordered)}, value=column, else_=len(ordered))
